using System.Net;
using System.Text.Encodings.Web;
using System.Text.Json;
using LoanSystem.Common.Core.Ports.Outbound;
using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Diagnostics;

namespace LoanSystem.Common.Adapters.Persistence;

/// <summary>
/// Writes one <see cref="AuditLogRecord"/> per added/modified/deleted entity (BE-SEC-07). The records are
/// added to the same change tracker before saving, so they commit in the same SaveChanges/transaction as
/// the business data. Every dependency is optional so hosts without HTTP (Workers, tests) still work.
/// </summary>
public sealed class AuditLogInterceptor : SaveChangesInterceptor
{
    /// <summary>Entity id logged when the key is generated by the database and is not known yet.</summary>
    public const string PendingEntityId = "pending";

    private static readonly JsonSerializerOptions SerializerOptions = new()
    {
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
    };

    // Exact property names whose values must never reach the audit trail
    private static readonly HashSet<string> SensitivePropertyNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "Password",
        "PasswordHash",
        "TokenHash",
        "RefreshToken",
        "AccessToken"
    };

    private readonly ICurrentUser? _currentUser;
    private readonly IHttpContextAccessor? _httpContextAccessor;
    private readonly IAuditContext? _auditContext;
    private readonly IClock? _clock;

    public AuditLogInterceptor(
        ICurrentUser? currentUser = null,
        IHttpContextAccessor? httpContextAccessor = null,
        IAuditContext? auditContext = null,
        IClock? clock = null)
    {
        _currentUser = currentUser;
        _httpContextAccessor = httpContextAccessor;
        _auditContext = auditContext;
        _clock = clock;
    }

    public override InterceptionResult<int> SavingChanges(
        DbContextEventData eventData,
        InterceptionResult<int> result)
    {
        if (eventData.Context is not null)
        {
            ProcessAuditLogs(eventData.Context);
        }

        return base.SavingChanges(eventData, result);
    }

    public override ValueTask<InterceptionResult<int>> SavingChangesAsync(
        DbContextEventData eventData,
        InterceptionResult<int> result,
        CancellationToken cancellationToken = default)
    {
        if (eventData.Context is not null)
        {
            ProcessAuditLogs(eventData.Context);
        }

        return base.SavingChangesAsync(eventData, result, cancellationToken);
    }

    private void ProcessAuditLogs(DbContext context)
    {
        var entries = context.ChangeTracker
            .Entries()
            .Where(e => e.Entity is not AuditLogRecord
                     && e.Entity is not OutboxMessage
                     && !e.Metadata.IsExcludedFromAudit()
                     && e.State is EntityState.Added or EntityState.Modified or EntityState.Deleted)
            .ToList();

        if (entries.Count == 0)
        {
            return;
        }

        // An actor set explicitly by the use case (login, refresh, reset) wins over the request's JWT,
        // which may belong to another user if the client still sends a stale Authorization header
        var userId = _auditContext?.ActorId ?? _currentUser?.UserId;
        var businessAction = _auditContext?.Action;
        var userIp = _httpContextAccessor?.HttpContext?.Connection.RemoteIpAddress;
        if (userIp is { IsIPv4MappedToIPv6: true })
        {
            userIp = userIp.MapToIPv4();
        }

        var userAgent = _httpContextAccessor?.HttpContext?.Request.Headers.UserAgent.ToString();
        if (string.IsNullOrWhiteSpace(userAgent))
        {
            userAgent = null;
        }

        // timestamptz only accepts UTC offsets in Npgsql
        var createdAt = (_clock?.UtcNow ?? DateTimeOffset.UtcNow).ToUniversalTime();
        var records = new List<AuditLogRecord>(entries.Count);

        foreach (var entry in entries)
        {
            var entityName = entry.Metadata.GetTableName() ?? entry.Metadata.ClrType.Name;
            var entityId = GetEntityId(entry);

            string action;
            string? stateBefore = null;
            string? stateAfter = null;

            switch (entry.State)
            {
                case EntityState.Added:
                    action = businessAction ?? "CREATE";
                    stateAfter = SerializeState(entry, isOriginal: false);
                    break;

                case EntityState.Modified:
                    action = businessAction ?? "UPDATE";
                    stateBefore = SerializeState(entry, isOriginal: true);
                    stateAfter = SerializeState(entry, isOriginal: false);
                    break;

                case EntityState.Deleted:
                    // A physical delete is always recorded as such, whatever the business action
                    action = "DELETE";
                    stateBefore = SerializeState(entry, isOriginal: true);
                    break;

                default:
                    continue;
            }

            records.Add(new AuditLogRecord
            {
                EntityName = entityName,
                EntityId = entityId,
                Action = action,
                StateBefore = stateBefore,
                StateAfter = stateAfter,
                UserId = userId,
                UserIp = userIp,
                UserAgent = userAgent,
                CreatedAt = createdAt
            });
        }

        if (records.Count > 0)
        {
            context.Set<AuditLogRecord>().AddRange(records);
        }
    }

    private static string GetEntityId(EntityEntry entry)
    {
        var primaryKey = entry.Metadata.FindPrimaryKey();
        if (primaryKey is null || primaryKey.Properties.Count == 0)
        {
            var idProperty = entry.Properties.FirstOrDefault(p =>
                string.Equals(p.Metadata.Name, "Id", StringComparison.OrdinalIgnoreCase));
            return idProperty is null ? "0" : ReadKeyValue(entry, idProperty)?.ToString() ?? "0";
        }

        var keyProperties = primaryKey.Properties.Select(p => entry.Property(p.Name)).ToList();

        // Database-generated keys only exist after the INSERT; EF holds a temporary placeholder until then.
        // audit_logs is append-only, so the id cannot be patched afterwards: record it as pending.
        if (keyProperties.Any(p => p.IsTemporary))
        {
            return PendingEntityId;
        }

        if (keyProperties.Count == 1)
        {
            return ReadKeyValue(entry, keyProperties[0])?.ToString() ?? "0";
        }

        return string.Join(",", keyProperties.Select(p => $"{p.Metadata.Name}={ReadKeyValue(entry, p)}"));
    }

    private static object? ReadKeyValue(EntityEntry entry, PropertyEntry property) =>
        entry.State == EntityState.Deleted
            ? property.OriginalValue ?? property.CurrentValue
            : property.CurrentValue ?? property.OriginalValue;

    private static string SerializeState(EntityEntry entry, bool isOriginal)
    {
        var values = new Dictionary<string, object?>();

        foreach (var property in entry.Properties)
        {
            var name = property.Metadata.Name;
            if (property.Metadata.IsAuditSensitive() || IsSensitiveName(name))
            {
                values[name] = "[REDACTED]";
                continue;
            }

            var val = isOriginal ? property.OriginalValue : property.CurrentValue;
            values[name] = val switch
            {
                IPAddress ip => ip.ToString(),
                Enum e => e.ToString(),
                _ => val
            };
        }

        return JsonSerializer.Serialize(values, SerializerOptions);
    }

    // Naming rules are a safety net; properties with other names are marked with IsAuditSensitive() in the EF mapping.
    // Deliberately narrow: plain "token"/"code" substrings would hide useful data (TokenExpiresAt, CurrencyCode).
    private static bool IsSensitiveName(string name) =>
        SensitivePropertyNames.Contains(name)
        || name.Contains("secret", StringComparison.OrdinalIgnoreCase)
        || name.EndsWith("Hash", StringComparison.OrdinalIgnoreCase)
        // NewPassword, TemporaryPassword... but not timestamps such as PasswordChangedAt
        || (name.Contains("password", StringComparison.OrdinalIgnoreCase)
            && !name.EndsWith("At", StringComparison.Ordinal));
}
