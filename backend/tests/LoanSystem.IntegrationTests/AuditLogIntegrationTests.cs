using Testcontainers.PostgreSql;
using Xunit;

namespace LoanSystem.IntegrationTests;

/// <summary>
/// BE-SEC-07 against a real PostgreSQL: jsonb/inet/user_agent mapping and that audit rows
/// commit or roll back together with the business data (same SaveChanges transaction).
/// </summary>
public class AuditLogIntegrationTests : IAsyncLifetime
{
    private const string CreateTestTableSql = """
        CREATE TABLE audit_it_items (
            id     BIGSERIAL     PRIMARY KEY,
            code   VARCHAR(20)   NOT NULL UNIQUE,
            amount NUMERIC(12,2) NOT NULL
        );
        """;

    private sealed class AuditItItem
    {
        public long Id { get; set; }
        public string Code { get; set; } = string.Empty;
        public decimal Amount { get; set; }
    }

    // Same base as every module DbContext, with a table whose key is generated by the database
    private sealed class TestModuleDbContext(DbContextOptions<TestModuleDbContext> options) : ModuleDbContext(options)
    {
        public DbSet<AuditItItem> Items => Set<AuditItItem>();

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            base.OnModelCreating(modelBuilder);
            modelBuilder.Entity<AuditItItem>(b =>
            {
                b.ToTable("audit_it_items");
                b.HasKey(i => i.Id);
                b.Property(i => i.Id).HasColumnName("id").ValueGeneratedOnAdd();
                b.Property(i => i.Code).HasColumnName("code");
                b.Property(i => i.Amount).HasColumnName("amount");
            });
        }
    }

    private sealed class FixedCurrentUser(Guid userId) : ICurrentUser
    {
        public Guid? UserId => userId;
        public string? Email => null;
        public IReadOnlyCollection<string> Roles => [];
        public Guid? CustomerId => null;
        public bool IsAuthenticated => true;
        public bool IsInRole(string role) => false;
    }

    private PostgreSqlContainer? _postgresContainer;
    private bool _dockerAvailable = true;

    public async Task InitializeAsync()
    {
        try
        {
            _postgresContainer = new PostgreSqlBuilder("postgres:17-alpine")
                .WithDatabase("loan_system_audit_test")
                .WithUsername("postgres")
                .WithPassword("postgrespassword")
                .Build();

            await _postgresContainer.StartAsync();
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Docker not available or failed to start: {ex.Message}");
            _dockerAvailable = false;
        }
    }

    public async Task DisposeAsync()
    {
        if (_postgresContainer is not null)
        {
            await _postgresContainer.DisposeAsync();
        }
    }

    [Fact]
    public async Task SaveChanges_PersistsAuditRow_WithJsonbInetAndUserAgent()
    {
        if (!_dockerAvailable || _postgresContainer is null)
        {
            // Skip assertion if Docker is not active on host machine
            return;
        }

        var connectionString = await PrepareDatabaseAsync();
        var userId = await InsertUserAsync(connectionString);

        AuditItItem item;
        await using (var context = CreateContext(connectionString, userId))
        {
            item = new AuditItItem { Code = "IT-001", Amount = 150.50m };
            context.Items.Add(item);
            await context.SaveChangesAsync();

            item.Amount = 200m;
            await context.SaveChangesAsync();
        }

        await using var connection = new NpgsqlConnection(connectionString);
        var rows = (await connection.QueryAsync<AuditRow>(
            """
            SELECT action, entity_id AS EntityId, user_id AS UserId, host(user_ip) AS UserIp, user_agent AS UserAgent,
                   jsonb_typeof(state_after) AS StateAfterType,
                   state_before ->> 'Amount' AS AmountBefore, state_after ->> 'Amount' AS AmountAfter,
                   state_after ->> 'Code' AS CodeAfter
            FROM audit_logs
            WHERE entity_name = 'audit_it_items'
            ORDER BY id
            """)).ToList();

        rows.Count.ShouldBe(2);

        var create = rows[0];
        create.Action.ShouldBe("CREATE");
        create.EntityId.ShouldBe(AuditLogInterceptor.PendingEntityId); // BIGSERIAL: id unknown before INSERT
        create.StateAfterType.ShouldBe("object");                     // stored as real jsonb
        create.CodeAfter.ShouldBe("IT-001");
        create.UserId.ShouldBe(userId);
        create.UserIp.ShouldBe("203.0.113.7");                         // stored as inet
        create.UserAgent.ShouldBe("LoanApp/2.0 (Android 14)");

        var update = rows[1];
        update.Action.ShouldBe("UPDATE");
        update.EntityId.ShouldBe(item.Id.ToString());
        update.AmountBefore.ShouldBe("150.50");
        update.AmountAfter.ShouldBe("200");
    }

    [Fact]
    public async Task FailedSaveChanges_RollsBackBusinessRowsAndAuditRowsTogether()
    {
        if (!_dockerAvailable || _postgresContainer is null)
        {
            // Skip assertion if Docker is not active on host machine
            return;
        }

        var connectionString = await PrepareDatabaseAsync();
        var userId = await InsertUserAsync(connectionString);

        await using (var context = CreateContext(connectionString, userId))
        {
            context.Items.Add(new AuditItItem { Code = "EXISTING", Amount = 1m });
            await context.SaveChangesAsync();
        }

        // One SaveChanges with a valid row and a duplicate code: the UNIQUE violation must undo everything
        await using (var context = CreateContext(connectionString, userId))
        {
            context.Items.Add(new AuditItItem { Code = "NEW-OK", Amount = 10m });
            context.Items.Add(new AuditItItem { Code = "EXISTING", Amount = 20m });

            await Should.ThrowAsync<DbUpdateException>(() => context.SaveChangesAsync());
        }

        await using var connection = new NpgsqlConnection(connectionString);
        (await connection.ExecuteScalarAsync<long>(
            "SELECT COUNT(*) FROM audit_it_items WHERE code = 'NEW-OK'")).ShouldBe(0);
        (await connection.ExecuteScalarAsync<long>(
            "SELECT COUNT(*) FROM audit_logs WHERE entity_name = 'audit_it_items' AND state_after ->> 'Code' = 'NEW-OK'")).ShouldBe(0);

        // Only the first, successful SaveChanges left its audit row
        (await connection.ExecuteScalarAsync<long>(
            "SELECT COUNT(*) FROM audit_logs WHERE entity_name = 'audit_it_items'")).ShouldBe(1);
    }

    [Fact]
    public async Task AuditLogs_AreAppendOnly_RejectUpdateAndDelete()
    {
        if (!_dockerAvailable || _postgresContainer is null)
            return;

        var connectionString = await PrepareDatabaseAsync();
        var userId = await InsertUserAsync(connectionString);

        await using (var ctx = CreateContext(connectionString, userId))
        {
            ctx.Items.Add(new AuditItItem { Code = "AUD-APP-1", Amount = 100m });
            await ctx.SaveChangesAsync();
        }

        await using var connection = new NpgsqlConnection(connectionString);

        var updateEx = await Should.ThrowAsync<PostgresException>(() =>
            connection.ExecuteAsync("UPDATE audit_logs SET action = 'ALTERED' WHERE entity_name = 'audit_it_items'"));
        updateEx.Message.ShouldContain("audit_logs es append-only");

        var deleteEx = await Should.ThrowAsync<PostgresException>(() =>
            connection.ExecuteAsync("DELETE FROM audit_logs WHERE entity_name = 'audit_it_items'"));
        deleteEx.Message.ShouldContain("audit_logs es append-only");

        var truncateEx = await Should.ThrowAsync<PostgresException>(() =>
            connection.ExecuteAsync("TRUNCATE audit_logs"));
        truncateEx.Message.ShouldContain("audit_logs es append-only");
    }

    [Fact]
    public async Task AuditLogReader_QueriesAuditRows_WithFiltersAndPagination()
    {
        if (!_dockerAvailable || _postgresContainer is null)
            return;

        var connectionString = await PrepareDatabaseAsync();
        var userId = await InsertUserAsync(connectionString);

        await using (var ctx = CreateContext(connectionString, userId))
        {
            ctx.Items.Add(new AuditItItem { Code = "AUD-QUERY-1", Amount = 250m });
            await ctx.SaveChangesAsync();
        }

        var reader = new LoanSystem.Modules.Security.Adapters.Outbound.Persistence.AuditLogReader(
            new NpgsqlConnectionFactory(connectionString));

        var query = new LoanSystem.Modules.Security.Core.Contracts.AuditLogQuery(
            EntityName: "audit_it_items",
            Action: "CREATE",
            Page: 1,
            PageSize: 10);

        var result = await reader.QueryAsync(query);

        result.Total.ShouldBeGreaterThanOrEqualTo(1);
        result.Items.ShouldContain(i => i.EntityName == "audit_it_items" && i.Action == "CREATE");
        var item = result.Items.First(i => i.EntityName == "audit_it_items");
        item.UserId.ShouldBe(userId);
        item.UserName.ShouldBe("Audit Integration");
        item.UserIp.ShouldBe("203.0.113.7");
        item.UserAgent.ShouldBe("LoanApp/2.0 (Android 14)");
        item.StateAfter.ShouldNotBeNull();
    }

    private sealed record AuditRow(
        string Action, string EntityId, Guid? UserId, string? UserIp, string? UserAgent,
        string? StateAfterType, string? AmountBefore, string? AmountAfter, string? CodeAfter);

    private async Task<string> PrepareDatabaseAsync()
    {
        var connectionString = _postgresContainer!.GetConnectionString();
        var migration = LoanSystem.DbMigrator.Program.Upgrade(connectionString, LoanSystem.DbMigrator.Program.FindDatabaseDirectory()!);
        migration.Successful.ShouldBeTrue($"DbMigrator failed with: {migration.Error}");

        await using var connection = new NpgsqlConnection(connectionString);
        await connection.ExecuteAsync(CreateTestTableSql);
        return connectionString;
    }

    // audit_logs.user_id references users(id), so the acting user must exist
    private static async Task<Guid> InsertUserAsync(string connectionString)
    {
        var userId = Guid.NewGuid();
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.ExecuteAsync(
            """
            INSERT INTO users (id, email, password_hash, full_name, role)
            VALUES (@Id, @Email, 'not-a-real-hash', 'Audit Integration', 'ROLE_ADMIN')
            """,
            new { Id = userId, Email = $"audit-{userId:N}@loan.test" });
        return userId;
    }

    private static TestModuleDbContext CreateContext(string connectionString, Guid userId)
    {
        var httpContext = new DefaultHttpContext();
        httpContext.Connection.RemoteIpAddress = IPAddress.Parse("203.0.113.7");
        httpContext.Request.Headers.UserAgent = "LoanApp/2.0 (Android 14)";

        var interceptor = new AuditLogInterceptor(
            new FixedCurrentUser(userId),
            new HttpContextAccessor { HttpContext = httpContext });

        var options = new DbContextOptionsBuilder<TestModuleDbContext>()
            .UseNpgsql(connectionString)
            .AddInterceptors(interceptor)
            .Options;

        return new TestModuleDbContext(options);
    }
}
